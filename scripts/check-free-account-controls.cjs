'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {mergeFreeRules} = require('./free-control-rules.cjs');
const original = {rules:{'.read':false,'.write':false,users:{$uid:{'.read':'auth != null && auth.uid === $uid','.write':'auth != null && auth.uid === $uid','.validate':'newData.hasChildren()'}},rooms:{'.read':false},admins:{$uid:{'.read':'auth != null && auth.uid === $uid'}}}};
const merged = mergeFreeRules(original);
assert.equal(merged.rules.users.$uid['.read'],original.rules.users.$uid['.read']);
assert.equal(merged.rules.users.$uid['.write'],original.rules.users.$uid['.write']);
assert.equal(merged.rules.users.$uid['.validate'],original.rules.users.$uid['.validate']);
assert.ok(merged.rules.users.$uid.songs.$songId['.write'].includes('!data.exists()'));
assert.equal(merged.rules.users.$uid.songs['.write'],undefined);
assert.equal(merged.rules.rooms['.read'], original.rules.rooms['.read']);
assert.ok(merged.rules.rooms.$roomId['.validate'].includes('google.com')); 
assert.deepEqual(merged.rules.admins, original.rules.admins);
assert.equal(original.rules.adminClientControl, undefined);
assert.deepEqual(mergeFreeRules(merged), merged);
assert.throws(() => mergeFreeRules({rules:{'.read':true}}));
assert.throws(() => mergeFreeRules({rules:{$other:{'.read':true}}}));
const root = path.join(__dirname, '..');
for (const file of ['admin-control-api.js','admin-client-controls.js','admin-account-controls.js','admin-mylist-core.js','admin-mylist-service.js','admin-mylist-ui.js']) new vm.Script(fs.readFileSync(path.join(root,file),'utf8'),{filename:file});
const api = fs.readFileSync(path.join(root,'admin-control-api.js'),'utf8');
assert.ok(!api.includes('cloudfunctions.net'));
assert.ok(!api.includes('revokeRefreshTokens'));
const disabled = fs.readFileSync(path.join(root,'.github/workflows/deploy-firebase-functions.yml'),'utf8');
assert.ok(!disabled.includes('firebase deploy'));
assert.ok(!/^\s+push:/m.test(disabled));
const workflow = fs.readFileSync(path.join(root,'.github/workflows/apply-free-admin-controls.yml'),'utf8');
assert.ok(!workflow.includes('firebase deploy'));
assert.ok(!workflow.includes('firebase-tools'));
assert.ok(workflow.includes('configure-free-account-controls.cjs --apply'));
console.log('PASS: unrelated access rules preserved; repeat application is stable; unsafe root grants rejected; browser scripts parse; no Functions deployment or token revocation.');


